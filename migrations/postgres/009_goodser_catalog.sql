-- 009_goodser_catalog.sql
-- Goodser V3.3：谷子图鉴、识别与导出
-- 图鉴用于辅助识别：一张图鉴可包含多张原图，单张原图可切割出多个柄图
-- 迁移器按英文分号拆分执行，本文件注释与字符串内不得出现英文分号

-- ============================================================
-- 1. 谷子图鉴
-- ============================================================
CREATE TABLE IF NOT EXISTS zzz_goodser_catalogs (
  id             varchar(36) PRIMARY KEY,
  inventory_id   varchar(36),
  title          varchar(200) NOT NULL,
  remark         text,
  cover_url      varchar(1024),
  status         varchar(20) NOT NULL DEFAULT 'active',
  owner_user_id  bigint,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE zzz_goodser_catalogs IS '商品服务-谷子图鉴';
CREATE INDEX IF NOT EXISTS idx_goodser_catalogs_inventory ON zzz_goodser_catalogs (inventory_id, status);
CREATE INDEX IF NOT EXISTS idx_goodser_catalogs_owner ON zzz_goodser_catalogs (owner_user_id);

CREATE TABLE IF NOT EXISTS zzz_goodser_catalog_images (
  id            varchar(36) PRIMARY KEY,
  catalog_id    varchar(36) NOT NULL REFERENCES zzz_goodser_catalogs(id) ON DELETE CASCADE,
  image_url     varchar(1024) NOT NULL,
  width         integer NOT NULL DEFAULT 0,
  height        integer NOT NULL DEFAULT 0,
  crop_status   varchar(20) NOT NULL DEFAULT 'pending',
  crop_error    text,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE zzz_goodser_catalog_images IS '商品服务-图鉴原图（单张可含多个柄图）';
CREATE INDEX IF NOT EXISTS idx_goodser_catalog_images_catalog ON zzz_goodser_catalog_images (catalog_id, created_at);
CREATE INDEX IF NOT EXISTS idx_goodser_catalog_images_status ON zzz_goodser_catalog_images (crop_status);

CREATE TABLE IF NOT EXISTS zzz_goodser_catalog_items (
  id             varchar(36) PRIMARY KEY,
  catalog_id     varchar(36) NOT NULL REFERENCES zzz_goodser_catalogs(id) ON DELETE CASCADE,
  image_id       varchar(36) REFERENCES zzz_goodser_catalog_images(id) ON DELETE CASCADE,
  product_id     varchar(36),
  title          varchar(200) NOT NULL DEFAULT '',
  remark         text,
  image_url      varchar(1024) NOT NULL,
  thumb_url      varchar(1024),
  box            jsonb,
  sort_order     integer NOT NULL DEFAULT 0,
  status         varchar(20) NOT NULL DEFAULT 'active',
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE zzz_goodser_catalog_items IS '商品服务-图鉴柄图（切割后的小图）';
CREATE INDEX IF NOT EXISTS idx_goodser_catalog_items_catalog ON zzz_goodser_catalog_items (catalog_id, sort_order);
CREATE INDEX IF NOT EXISTS idx_goodser_catalog_items_image ON zzz_goodser_catalog_items (image_id);
CREATE INDEX IF NOT EXISTS idx_goodser_catalog_items_product ON zzz_goodser_catalog_items (product_id);

-- ============================================================
-- 2. 识别任务与复核
-- ============================================================
CREATE TABLE IF NOT EXISTS zzz_goodser_recognition_jobs (
  id            varchar(36) PRIMARY KEY,
  inventory_id  varchar(36) NOT NULL,
  image_url     varchar(1024) NOT NULL,
  mode          varchar(20) NOT NULL DEFAULT 'multi',
  status        varchar(20) NOT NULL DEFAULT 'pending',
  result        jsonb,
  error         text,
  created_by    bigint,
  created_at    timestamptz NOT NULL DEFAULT now(),
  finished_at   timestamptz
);
COMMENT ON TABLE zzz_goodser_recognition_jobs IS '商品服务-图片识别任务';
CREATE INDEX IF NOT EXISTS idx_goodser_recognition_jobs_inventory ON zzz_goodser_recognition_jobs (inventory_id, created_at);
CREATE INDEX IF NOT EXISTS idx_goodser_recognition_jobs_status ON zzz_goodser_recognition_jobs (status);

CREATE TABLE IF NOT EXISTS zzz_goodser_recognition_items (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id          varchar(36) NOT NULL REFERENCES zzz_goodser_recognition_jobs(id) ON DELETE CASCADE,
  box             jsonb,
  crop_url        varchar(1024),
  product_id      varchar(36),
  catalog_item_id varchar(36),
  quantity        integer NOT NULL DEFAULT 1,
  confidence      numeric(5,4) NOT NULL DEFAULT 0,
  matched_by      varchar(20),
  alternatives    jsonb,
  confirmed       boolean NOT NULL DEFAULT false,
  created_at      timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE zzz_goodser_recognition_items IS '商品服务-识别项与人工复核结果';
CREATE INDEX IF NOT EXISTS idx_goodser_recognition_items_job ON zzz_goodser_recognition_items (job_id);
CREATE INDEX IF NOT EXISTS idx_goodser_recognition_items_product ON zzz_goodser_recognition_items (product_id);

CREATE TABLE IF NOT EXISTS zzz_goodser_recognition_feedback (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id        varchar(36) NOT NULL,
  item_id       bigint,
  predicted_id  varchar(36),
  actual_id     varchar(36),
  rating        smallint,
  note          text,
  created_by    bigint,
  created_at    timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE zzz_goodser_recognition_feedback IS '商品服务-识别人工反馈（评估/再训练）';
CREATE INDEX IF NOT EXISTS idx_goodser_recognition_feedback_job ON zzz_goodser_recognition_feedback (job_id);

-- ============================================================
-- 3. 向量元数据（向量本体由 goodser-vision/FAISS 维护，pgvector 就绪后再加 vector 列）
-- ============================================================
CREATE TABLE IF NOT EXISTS zzz_goodser_product_embeddings (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inventory_id  varchar(36) NOT NULL,
  source_type   varchar(20) NOT NULL DEFAULT 'product',
  source_id     varchar(36) NOT NULL,
  image_url     varchar(1024) NOT NULL,
  model         varchar(64) NOT NULL,
  dim           integer NOT NULL DEFAULT 512,
  embedding     jsonb,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  UNIQUE (source_type, source_id, image_url, model)
);
COMMENT ON TABLE zzz_goodser_product_embeddings IS '商品服务-图片向量元数据，source_type=product|catalog_item';
CREATE INDEX IF NOT EXISTS idx_goodser_embeddings_inventory ON zzz_goodser_product_embeddings (inventory_id, source_type);
CREATE INDEX IF NOT EXISTS idx_goodser_embeddings_source ON zzz_goodser_product_embeddings (source_type, source_id);

-- ============================================================
-- 4. 平铺图导出
-- ============================================================
CREATE TABLE IF NOT EXISTS zzz_goodser_export_jobs (
  id            varchar(36) PRIMARY KEY,
  inventory_id  varchar(36) NOT NULL,
  status        varchar(20) NOT NULL DEFAULT 'pending',
  request       jsonb NOT NULL,
  result_url    varchar(1024),
  error         text,
  created_by    bigint,
  created_at    timestamptz NOT NULL DEFAULT now(),
  finished_at   timestamptz,
  expires_at    timestamptz
);
COMMENT ON TABLE zzz_goodser_export_jobs IS '商品服务-平铺图导出任务';
CREATE INDEX IF NOT EXISTS idx_goodser_export_jobs_inventory ON zzz_goodser_export_jobs (inventory_id, created_at);
CREATE INDEX IF NOT EXISTS idx_goodser_export_jobs_status ON zzz_goodser_export_jobs (status);

CREATE TABLE IF NOT EXISTS zzz_goodser_export_templates (
  id            varchar(36) PRIMARY KEY,
  inventory_id  varchar(36),
  name          varchar(100) NOT NULL,
  config        jsonb NOT NULL,
  is_default    boolean NOT NULL DEFAULT false,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE zzz_goodser_export_templates IS '商品服务-平铺图导出模板';
CREATE INDEX IF NOT EXISTS idx_goodser_export_templates_inventory ON zzz_goodser_export_templates (inventory_id);

