CREATE TABLE IF NOT EXISTS scheduler_tasks (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255) NOT NULL,
    type         VARCHAR(20) NOT NULL DEFAULT 'cron',
    expression   VARCHAR(255) NOT NULL DEFAULT '',
    handler      VARCHAR(255) NOT NULL DEFAULT '',
    payload      JSONB,
    status       VARCHAR(20) NOT NULL DEFAULT 'active',
    max_retries  INTEGER NOT NULL DEFAULT 3,
    timeout      INTEGER NOT NULL DEFAULT 300,
    last_run_at  TIMESTAMPTZ,
    next_run_at  TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE scheduler_tasks IS '调度任务。expression 为 cron 或间隔表达式';
CREATE UNIQUE INDEX IF NOT EXISTS uk_scheduler_tasks_name ON scheduler_tasks (name);
CREATE INDEX IF NOT EXISTS idx_scheduler_tasks_status ON scheduler_tasks (status);
CREATE INDEX IF NOT EXISTS idx_scheduler_tasks_next_run ON scheduler_tasks (next_run_at);

CREATE TABLE IF NOT EXISTS scheduler_task_logs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id     BIGINT NOT NULL,
    task_name   VARCHAR(255) NOT NULL DEFAULT '',
    status      VARCHAR(20) NOT NULL DEFAULT '',
    started_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    ended_at    TIMESTAMPTZ,
    result      JSONB,
    error       TEXT NOT NULL DEFAULT '',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_scheduler_task_logs_task FOREIGN KEY (task_id)
        REFERENCES scheduler_tasks (id) ON DELETE CASCADE
);

COMMENT ON TABLE scheduler_task_logs IS '调度任务执行日志';
CREATE INDEX IF NOT EXISTS idx_scheduler_task_logs_task ON scheduler_task_logs (task_id);
CREATE INDEX IF NOT EXISTS idx_scheduler_task_logs_created ON scheduler_task_logs (created_at DESC);

