-- ============================================================
-- 1. Auth / RBAC
-- ============================================================

CREATE TABLE IF NOT EXISTS users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    VARCHAR(100) NOT NULL,
    password    VARCHAR(255) NOT NULL,
    nickname    VARCHAR(100) NOT NULL DEFAULT '',
    email       VARCHAR(255) NOT NULL DEFAULT '',
    avatar_url  VARCHAR(512) NOT NULL DEFAULT '',
    phone       VARCHAR(50) NOT NULL DEFAULT '',
    status      VARCHAR(20) NOT NULL DEFAULT 'active',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at  TIMESTAMPTZ
);

COMMENT ON TABLE users IS '系统用户。password 为 bcrypt 密文，软删除使用 deleted_at';
CREATE UNIQUE INDEX IF NOT EXISTS uk_users_username ON users (username) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_users_status ON users (status);
CREATE INDEX IF NOT EXISTS idx_users_deleted_at ON users (deleted_at);

CREATE TABLE IF NOT EXISTS roles (
    name        VARCHAR(50) PRIMARY KEY,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE roles IS '角色定义。name 直接作为主键，V3 默认 admin/user';

CREATE TABLE IF NOT EXISTS permissions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    resource    VARCHAR(100) NOT NULL DEFAULT '',
    action      VARCHAR(50) NOT NULL DEFAULT '',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE permissions IS '权限点。name 建议使用 resource:action 形式';
CREATE UNIQUE INDEX IF NOT EXISTS uk_permissions_name ON permissions (name);
CREATE INDEX IF NOT EXISTS idx_permissions_resource_action ON permissions (resource, action);

CREATE TABLE IF NOT EXISTS role_permissions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role           VARCHAR(50) NOT NULL,
    permission_id  BIGINT NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_role_permissions_permission FOREIGN KEY (permission_id)
        REFERENCES permissions (id) ON DELETE CASCADE
);

COMMENT ON TABLE role_permissions IS '角色与权限关联';
CREATE UNIQUE INDEX IF NOT EXISTS uk_role_permissions_role_permission
    ON role_permissions (role, permission_id);
CREATE INDEX IF NOT EXISTS idx_role_permissions_role ON role_permissions (role);
CREATE INDEX IF NOT EXISTS idx_role_permissions_permission ON role_permissions (permission_id);

CREATE TABLE IF NOT EXISTS user_roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL,
    role        VARCHAR(50) NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE
);

COMMENT ON TABLE user_roles IS '用户与角色关联';
CREATE UNIQUE INDEX IF NOT EXISTS uk_user_roles_user_role ON user_roles (user_id, role);
CREATE INDEX IF NOT EXISTS idx_user_roles_role ON user_roles (role);

CREATE TABLE IF NOT EXISTS api_keys (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    key_prefix    VARCHAR(10) NOT NULL,
    key_hash      VARCHAR(64) NOT NULL,
    user_id       BIGINT NOT NULL,
    scopes        VARCHAR(500) NOT NULL DEFAULT '*:*',
    last_used_at  TIMESTAMPTZ,
    expires_at    TIMESTAMPTZ,
    status        VARCHAR(20) NOT NULL DEFAULT 'active',
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at    TIMESTAMPTZ
);

COMMENT ON TABLE api_keys IS 'API Key。只保存哈希与前缀，明文只在创建时返回一次';
CREATE UNIQUE INDEX IF NOT EXISTS uk_api_keys_hash ON api_keys (key_hash) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_api_keys_user ON api_keys (user_id);
CREATE INDEX IF NOT EXISTS idx_api_keys_status ON api_keys (status);
CREATE INDEX IF NOT EXISTS idx_api_keys_deleted_at ON api_keys (deleted_at);

